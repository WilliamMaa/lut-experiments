"""
Multi-layer LUT replacement scan.

Phase 1: per-layer sensitivity scan across candidate layers and group counts.
Phase 2: cumulative multi-layer evaluation for selected configurations.

Assumes per-layer checkpoints generated by expand_ratio.py:
    {checkpoint_root}/expand_ratio_l{layer}/ckpt_g{count}/replacement_l{layer}g{gid}.pt

Usage:
    cd /data/mingyu/LLM_LUT/v3
    python multi_layer_scan.py \
        --model Qwen/Qwen2.5-7B-Instruct \
        --layers "19,20,21,22,23" \
        --group_counts "4,8,12,16" \
        --checkpoint_root results \
        --output_dir results/multi_layer_scan \
        --device cuda:1
"""

import os
import sys
import json
import glob
import argparse
from pathlib import Path

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

V0_DIR = os.path.join(os.path.dirname(__file__), "..", "v0")
sys.path.insert(0, V0_DIR)

from data import prepare_data, load_jsonl, TextDataset
from metrics import compute_baseline_probs, compute_model_metrics
from partial_linear import V3PartialEngine


def parse_int_list(s):
    return [int(x.strip()) for x in s.split(",")]


def load_model_and_data(model_name, eval_size, max_seq_len, batch_size, device_str="cuda:0"):
    device = torch.device(device_str)
    torch.cuda.set_device(device)

    tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        torch_dtype=torch.float16,
        device_map=device_str,
        low_cpu_mem_usage=True,
    )
    model.eval()
    for p in model.parameters():
        p.requires_grad_(False)

    for i in range(torch.cuda.device_count()):
        if i != device.index and torch.cuda.memory_allocated(i) > 0:
            print(f"[WARN] GPU {i} has allocated memory; proceeding because device_map={device_str} is explicit single-GPU.")

    calib_path = "../v0/data/calib.jsonl"
    eval_path = "../v0/data/eval.jsonl"
    prepare_data(tokenizer, calib_path, eval_path, calib_size=0, eval_size=eval_size, max_seq_len=max_seq_len)
    eval_texts = load_jsonl(eval_path)
    eval_dataset = TextDataset(eval_texts, tokenizer, max_seq_len=max_seq_len)
    eval_loader = eval_dataset.make_loader(batch_size=batch_size, shuffle=False)

    return model, tokenizer, eval_loader


def load_groups_for_layer(checkpoint_root, layer_id, group_count):
    """Return list of (group_id, checkpoint_path) for a layer config.

    Supports both new layout (checkpoints/ckpt_g{count}) and old layout (ckpt_g{count}).
    """
    candidates = [
        os.path.join(checkpoint_root, f"expand_ratio_l{layer_id}", "checkpoints", f"ckpt_g{group_count}"),
        os.path.join(checkpoint_root, f"expand_ratio_l{layer_id}", f"ckpt_g{group_count}"),
    ]
    prefix = f"replacement_l{layer_id}g"
    suffix = ".pt"
    for ckpt_dir in candidates:
        pattern = os.path.join(ckpt_dir, f"replacement_l{layer_id}g*.pt")
        paths = sorted(glob.glob(pattern))
        if not paths:
            continue
        groups = []
        for p in paths:
            name = os.path.basename(p)
            if not (name.startswith(prefix) and name.endswith(suffix)):
                continue
            gid = int(name[len(prefix):-len(suffix)])
            groups.append((gid, p))
        return groups
    return []


def build_engine(model, layer_id, group_count, checkpoint_root):
    """Build and return a V3PartialEngine for one layer config."""
    groups = load_groups_for_layer(checkpoint_root, layer_id, group_count)
    if not groups:
        raise ValueError(f"No checkpoints found for L{layer_id} G{group_count} in {checkpoint_root}")
    if len(groups) != group_count:
        print(f"[WARN] L{layer_id} G{group_count}: expected {group_count} checkpoints, found {len(groups)}")

    engine = V3PartialEngine(model, layer_id, group_size=64, num_bins=64)
    for gid, path in groups:
        ckpt = torch.load(path, map_location="cpu")
        engine.add_group(
            group_id=gid,
            addr_idx=ckpt["addr_idx"],
            addr_mean=ckpt["addr_mean"],
            addr_std=ckpt["addr_std"],
            table=ckpt["table"],
        )
    return engine


def evaluate_single_layer(model, eval_loader, reference_probs, layer_id, group_count, checkpoint_root):
    """Evaluate one layer config; return metrics dict."""
    engine = build_engine(model, layer_id, group_count, checkpoint_root)
    engine.install()
    try:
        metrics = compute_model_metrics(model, eval_loader, reference_probs_list=reference_probs)
    finally:
        engine.uninstall()
    return metrics


def evaluate_multi_layer(model, eval_loader, reference_probs, configs, checkpoint_root):
    """Evaluate a list of (layer_id, group_count) configs installed simultaneously."""
    engines = []
    try:
        for layer_id, group_count in configs:
            engine = build_engine(model, layer_id, group_count, checkpoint_root)
            engine.install()
            engines.append(engine)
        metrics = compute_model_metrics(model, eval_loader, reference_probs_list=reference_probs)
    finally:
        for engine in reversed(engines):
            engine.uninstall()
    return metrics


def compute_mac_reduction(configs, hidden_size, intermediate_size, num_layers):
    """Compute full-model major-linear MAC reduction ratio for a multi-layer config.

    Assumes each Transformer block has 4 attention linears + 3 MLP linears.
    """
    per_layer_total = 4 * hidden_size * hidden_size + 3 * hidden_size * intermediate_size
    full_model_total = num_layers * per_layer_total
    eliminated = sum(count * 64 * intermediate_size for _, count in configs)
    return eliminated / full_model_total


def compute_lut_storage(configs, checkpoint_root):
    """Compute total LUT table bytes for a multi-layer config."""
    total_bytes = 0
    for layer_id, group_count in configs:
        groups = load_groups_for_layer(checkpoint_root, layer_id, group_count)
        for _, path in groups:
            ckpt = torch.load(path, map_location="cpu")
            table = ckpt["table"]
            total_bytes += table.element_size() * table.numel()
    return total_bytes


def format_bytes(n):
    for unit in ["B", "KiB", "MiB", "GiB"]:
        if n < 1024:
            return f"{n:.2f} {unit}"
        n /= 1024
    return f"{n:.2f} TiB"


def main():
    parser = argparse.ArgumentParser(description="Multi-layer LUT replacement scan")
    parser.add_argument("--model", default="Qwen/Qwen2.5-7B-Instruct")
    parser.add_argument("--layers", default="19,20,21,22,23", help="Comma-separated candidate layer IDs")
    parser.add_argument("--group_counts", default="4,8,12,16", help="Comma-separated group counts to test per layer")
    parser.add_argument("--checkpoint_root", default="outputs", help="Root dir containing expand_ratio_l{layer}/ckpt_g{count}")
    parser.add_argument("--eval_size", type=int, default=128)
    parser.add_argument("--max_seq_len", type=int, default=512)
    parser.add_argument("--batch_size", type=int, default=4)
    parser.add_argument("--output_dir", default="results/multi_layer_scan")
    parser.add_argument("--device", default="cuda:0", help="CUDA device to use (e.g. cuda:0, cuda:3)")
    args = parser.parse_args()

    Path(args.output_dir).mkdir(parents=True, exist_ok=True)
    layers = parse_int_list(args.layers)
    group_counts = parse_int_list(args.group_counts)

    print("=" * 70)
    print("Multi-Layer LUT Replacement Scan")
    print("=" * 70)
    print(f"Layers: {layers}")
    print(f"Group counts per layer: {group_counts}")
    print(f"Checkpoint root: {args.checkpoint_root}")
    print(f"Device: {args.device}")
    print("=" * 70)

    # Load model and data once
    print("\n[1/3] Loading model and data...")
    model, tokenizer, eval_loader = load_model_and_data(
        args.model, args.eval_size, args.max_seq_len, args.batch_size, device_str=args.device
    )
    hidden_size = model.config.hidden_size
    intermediate_size = model.config.intermediate_size
    num_layers = model.config.num_hidden_layers
    device = next(model.parameters()).device

    # Compute baseline reference probabilities (original model, no LUT)
    print("\n[2/3] Computing baseline reference probabilities...")
    model.eval()
    with torch.no_grad():
        reference_probs = compute_baseline_probs(model, eval_loader)
    baseline_metrics = compute_model_metrics(model, eval_loader, reference_probs_list=None)
    print(f"  Baseline: PPL={baseline_metrics['ppl']:.2f}, Acc={baseline_metrics['next_token_acc']:.4f}")

    # Phase 1: per-layer sensitivity scan
    print("\n[3/3] Phase 1: Per-layer sensitivity scan...")
    per_layer_results = {}
    for layer_id in layers:
        per_layer_results[layer_id] = {}
        for count in group_counts:
            print(f"  L{layer_id} {count:2d} groups ...", end=" ")
            try:
                metrics = evaluate_single_layer(model, eval_loader, reference_probs, layer_id, count, args.checkpoint_root)
                per_layer_results[layer_id][count] = {
                    "kl": metrics.get("avg_kl", 0.0),
                    "ppl": metrics["ppl"],
                    "acc": metrics["next_token_acc"],
                }
                print(f"KL={metrics.get('avg_kl', 0):.4f}, PPL={metrics['ppl']:.2f}, Acc={metrics['next_token_acc']:.4f}")
            except Exception as e:
                print(f"FAILED: {e}")
                per_layer_results[layer_id][count] = {"error": str(e)}

    # Phase 2: cumulative multi-layer evaluation for a few canonical configs
    print("\n[4/4] Phase 2: Cumulative multi-layer evaluation...")
    max_count = max(group_counts)

    cumulative_configs = [
        ("all_layers_max", [(lid, max_count) for lid in layers]),
        ("all_layers_half", [(lid, max_count // 2) for lid in layers]),
    ]
    # If only a few layers, also test conservative configs
    if len(layers) >= 4:
        mid = len(layers) // 2
        cumulative_configs.append(("middle_half_max", [(lid, max_count) for lid in layers[mid:mid+len(layers)//2]]))

    cumulative_results = []
    for name, configs in cumulative_configs:
        print(f"  Config '{name}': {configs} ...", end=" ")
        try:
            metrics = evaluate_multi_layer(model, eval_loader, reference_probs, configs, args.checkpoint_root)
            mac_ratio = compute_mac_reduction(configs, hidden_size, intermediate_size, num_layers)
            storage_bytes = compute_lut_storage(configs, args.checkpoint_root)
            entry = {
                "name": name,
                "configs": configs,
                "kl": metrics.get("avg_kl", 0.0),
                "ppl": metrics["ppl"],
                "acc": metrics["next_token_acc"],
                "mac_reduction_ratio": mac_ratio,
                "lut_storage_bytes": storage_bytes,
                "lut_storage_human": format_bytes(storage_bytes),
            }
            cumulative_results.append(entry)
            print(f"KL={entry['kl']:.4f}, PPL={entry['ppl']:.2f}, Acc={entry['acc']:.4f}, "
                  f"MAC↓={mac_ratio*100:.2f}%, LUT={format_bytes(storage_bytes)}")
        except Exception as e:
            print(f"FAILED: {e}")
            cumulative_results.append({"name": name, "configs": configs, "error": str(e)})

    # Save results
    summary = {
        "model": args.model,
        "layers": layers,
        "group_counts": group_counts,
        "hidden_size": hidden_size,
        "intermediate_size": intermediate_size,
        "num_layers": num_layers,
        "baseline": {
            "ppl": baseline_metrics["ppl"],
            "acc": baseline_metrics["next_token_acc"],
        },
        "per_layer": per_layer_results,
        "cumulative": cumulative_results,
    }

    output_path = os.path.join(args.output_dir, "multi_layer_scan.json")
    with open(output_path, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"\n[Saved] {output_path}")

    # Print summary table
    print("\n" + "=" * 70)
    print("PER-LAYER SENSITIVITY")
    print("=" * 70)
    header = f"{'Layer':>6} | " + " | ".join(f"G{c:>2}" for c in group_counts)
    print(header)
    print("-" * len(header))
    for layer_id in layers:
        row = f"{layer_id:>6} | "
        cells = []
        for count in group_counts:
            r = per_layer_results[layer_id].get(count, {})
            if "error" in r:
                cells.append("ERR")
            else:
                cells.append(f"KL={r['kl']:.3f}")
        row += " | ".join(cells)
        print(row)

    print("\n" + "=" * 70)
    print("CUMULATIVE CONFIGURATIONS")
    print("=" * 70)
    for entry in cumulative_results:
        if "error" in entry:
            print(f"{entry['name']}: ERROR {entry['error']}")
        else:
            print(f"{entry['name']}: KL={entry['kl']:.4f}, PPL={entry['ppl']:.2f}, "
                  f"MAC↓={entry['mac_reduction_ratio']*100:.2f}%, LUT={entry['lut_storage_human']}")
    print("=" * 70)


if __name__ == "__main__":
    main()
